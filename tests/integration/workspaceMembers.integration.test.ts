import { randomUUID } from "node:crypto"
import request from "supertest"
import { describe, expect, it } from "vitest"

import { hashToken } from "../../src/services/notification.service.js"
import { pool } from "../../src/lib/db.js"
import { app, signupUser } from "../helpers.js"

async function makeOwnerWithCrawlPlus(label: string) {
  const owner = await signupUser(`${label}-owner`)
  await pool!.query(
    `insert into subscriptions (user_id, stripe_customer_id, plan, status) values ($1, $2, 'crawl_plus', 'active')`,
    [owner.user.id, `cus_${label}_${randomUUID()}`],
  )
  const created = await request(app)
    .post("/chatbots")
    .set("Authorization", `Bearer ${owner.session.access_token}`)
    .send({
      name: `${label} bot`,
      sources: [{ type: "pdf", label: "handbook.pdf", characters: 50, content: "Our support email is help@example.com." }],
    })
  if (created.status !== 201) {
    throw new Error(`makeOwnerWithCrawlPlus: create failed: ${created.status} ${JSON.stringify(created.body)}`)
  }
  const chatbotId = created.body.chatbot.id as string
  return { owner, chatbotId }
}

async function inviteAndAccept(ownerToken: string, role: "admin" | "viewer", label: string) {
  const invite = await request(app)
    .post("/account/members/invite")
    .set("Authorization", `Bearer ${ownerToken}`)
    .send({ email: `${label}-${randomUUID()}@example.test`, role })
  expect(invite.status).toBe(201)

  const { rows } = await pool!.query<{ email: string }>(`select email from workspace_invitations where id = $1`, [invite.body.invitation.id])
  const email = rows[0].email

  // The service hashes the real token and only ever emails it — fetch it
  // straight out of the DB isn't possible (it's hashed at rest, same
  // pattern as email verification), so re-derive a token with a known
  // value by inserting it ourselves is wrong too. Instead: capture the
  // token the service generated by reading the (test-only) logged email
  // body isn't available here either, so for tests we re-issue a known
  // token hash directly — mirrors how other suites seed state directly
  // rather than parsing outbound email.
  const rawToken = randomUUID()
  await pool!.query(`update workspace_invitations set token_hash = $1 where id = $2`, [hashToken(rawToken), invite.body.invitation.id])

  const member = await signupUser(label)
  await pool!.query(`update users set email = $1 where id = $2`, [email, member.user.id])

  const accept = await request(app)
    .post("/account/members/accept")
    .set("Authorization", `Bearer ${member.session.access_token}`)
    .send({ token: rawToken })
  expect(accept.status).toBe(200)

  return member
}

describe("Phase 2: workspace members", () => {
  it("an Admin member can list the owner's chatbots and a Viewer member cannot invite/remove/change roles", async () => {
    const { owner, chatbotId } = await makeOwnerWithCrawlPlus("roles")
    const admin = await inviteAndAccept(owner.session.access_token, "admin", "roles-admin")
    const viewer = await inviteAndAccept(owner.session.access_token, "viewer", "roles-viewer")

    const adminList = await request(app).get("/chatbots").set("Authorization", `Bearer ${admin.session.access_token}`)
    expect(adminList.status).toBe(200)
    expect(adminList.body.chatbots.some((c: { chatbot: { id: string } }) => c.chatbot.id === chatbotId)).toBe(true)

    const viewerInvite = await request(app)
      .post("/account/members/invite")
      .set("Authorization", `Bearer ${viewer.session.access_token}`)
      .send({ email: "nope@example.test", role: "viewer" })
    expect(viewerInvite.status).toBe(403)

    const adminInvite = await request(app)
      .post("/account/members/invite")
      .set("Authorization", `Bearer ${admin.session.access_token}`)
      .send({ email: "nope2@example.test", role: "viewer" })
    expect(adminInvite.status).toBe(403)
  })

  it("a Viewer member cannot create or modify chatbot resources (admin-only write)", async () => {
    const { owner, chatbotId } = await makeOwnerWithCrawlPlus("viewer-write")
    const viewer = await inviteAndAccept(owner.session.access_token, "viewer", "viewer-write-member")

    const res = await request(app)
      .patch(`/chatbots/${chatbotId}/theme`)
      .set("Authorization", `Bearer ${viewer.session.access_token}`)
      .send({ theme: { primaryColor: "#000000", bgColor: "#ffffff", textColor: "#111111" } })
    expect(res.status).toBe(403)
  })

  it("an Admin member uploading a document gets the owner's Crawl Plus caps (6 docs), not Free", async () => {
    const { owner, chatbotId } = await makeOwnerWithCrawlPlus("doc-caps")
    const admin = await inviteAndAccept(owner.session.access_token, "admin", "doc-caps-member")

    for (let i = 0; i < 6; i++) {
      await pool!.query(
        `insert into chatbot_documents (chatbot_id, file_name, file_type, file_size, status, chunk_count)
         values ($1, $2, 'txt', 12, 'ready', 1)`,
        [chatbotId, `existing-${i}.txt`],
      )
    }

    const res = await request(app)
      .post(`/chatbots/${chatbotId}/documents`)
      .set("Authorization", `Bearer ${admin.session.access_token}`)
      .attach("file", Buffer.from("seventh\n"), "seventh.txt")

    // 409 DOC_LIMIT_REACHED with limit=6 proves the Crawl Plus plan (not
    // Free's 402-disabled, and not some other default) was resolved via
    // the OWNER's subscription even though the admin member made the call.
    expect(res.status).toBe(409)
    expect(res.body).toMatchObject({ code: "DOC_LIMIT_REACHED", data: { limit: 6 } })
  })

  it("a stranger (not owner, not a member) gets 404 on the same chatbot a member can reach", async () => {
    const { owner, chatbotId } = await makeOwnerWithCrawlPlus("stranger")
    const admin = await inviteAndAccept(owner.session.access_token, "admin", "stranger-member")
    const stranger = await signupUser("stranger-user")

    const asMember = await request(app).get(`/chatbots/${chatbotId}`).set("Authorization", `Bearer ${admin.session.access_token}`)
    expect(asMember.status).toBe(200)

    const asStranger = await request(app).get(`/chatbots/${chatbotId}`).set("Authorization", `Bearer ${stranger.session.access_token}`)
    expect(asStranger.status).toBe(404)
  })

  it("removing a member denies their very next request — no caching", async () => {
    const { owner, chatbotId } = await makeOwnerWithCrawlPlus("remove")
    const admin = await inviteAndAccept(owner.session.access_token, "admin", "remove-member")

    const before = await request(app).get(`/chatbots/${chatbotId}`).set("Authorization", `Bearer ${admin.session.access_token}`)
    expect(before.status).toBe(200)

    const removeRes = await request(app)
      .delete(`/account/members/${admin.user.id}`)
      .set("Authorization", `Bearer ${owner.session.access_token}`)
    expect(removeRes.status).toBe(204)

    const after = await request(app).get(`/chatbots/${chatbotId}`).set("Authorization", `Bearer ${admin.session.access_token}`)
    expect(after.status).toBe(404)
  })

  it("an invite cannot be accepted by a user who already owns chatbots", async () => {
    const { owner } = await makeOwnerWithCrawlPlus("already-owns")

    const invite = await request(app)
      .post("/account/members/invite")
      .set("Authorization", `Bearer ${owner.session.access_token}`)
      .send({ email: `already-owns-target-${randomUUID()}@example.test`, role: "admin" })
    const { rows } = await pool!.query<{ email: string }>(`select email from workspace_invitations where id = $1`, [invite.body.invitation.id])
    const rawToken = randomUUID()
    await pool!.query(`update workspace_invitations set token_hash = $1 where id = $2`, [hashToken(rawToken), invite.body.invitation.id])

    const { owner: alreadyOwner } = await makeOwnerWithCrawlPlus("already-owns-target")
    await pool!.query(`update users set email = $1 where id = $2`, [rows[0].email, alreadyOwner.user.id])

    const accept = await request(app)
      .post("/account/members/accept")
      .set("Authorization", `Bearer ${alreadyOwner.session.access_token}`)
      .send({ token: rawToken })
    expect(accept.status).toBe(409)
  })

  it("Free plan (1 seat) cannot invite anyone", async () => {
    const owner = await signupUser("free-plan-invite")
    const res = await request(app)
      .post("/account/members/invite")
      .set("Authorization", `Bearer ${owner.session.access_token}`)
      .send({ email: "someone@example.test", role: "viewer" })
    expect(res.status).toBe(409)
  })

  it("seats.used counts pending invites, matching what the invite limit enforces", async () => {
    // Crawl Plus = 4 seats (owner + 3).
    const { owner } = await makeOwnerWithCrawlPlus("seat-count")
    const token = owner.session.access_token
    const invite = (email: string) =>
      request(app).post("/account/members/invite").set("Authorization", `Bearer ${token}`).send({ email, role: "viewer" })

    expect((await invite(`a-${randomUUID()}@example.test`)).status).toBe(201)
    expect((await invite(`b-${randomUUID()}@example.test`)).status).toBe(201)

    const listed = await request(app).get("/account/members").set("Authorization", `Bearer ${token}`)
    expect(listed.body.seats).toEqual({ used: 3, max: 4 })

    const lastEmail = `c-${randomUUID()}@example.test`
    expect((await invite(lastEmail)).status).toBe(201)
    const full = await request(app).get("/account/members").set("Authorization", `Bearer ${token}`)
    expect(full.body.seats).toEqual({ used: 4, max: 4 })
    expect((await invite(`d-${randomUUID()}@example.test`)).status).toBe(409)

    // Re-inviting an email that already holds a pending seat replaces that
    // invite instead of being refused for the seat it already occupies.
    expect((await invite(lastEmail)).status).toBe(201)
  })

  it("GET /auth/me reports the member's role and the OWNER's chatbots (not the member's own empty list)", async () => {
    const { owner, chatbotId } = await makeOwnerWithCrawlPlus("auth-me")
    const admin = await inviteAndAccept(owner.session.access_token, "admin", "auth-me-admin")

    const me = await request(app).get("/auth/me").set("Authorization", `Bearer ${admin.session.access_token}`)
    expect(me.status).toBe(200)
    expect(me.body.user.workspace).toMatchObject({ role: "admin", isOwner: false })
    expect(me.body.user.chatbots.some((c: { id: string }) => c.id === chatbotId)).toBe(true)

    const ownerMe = await request(app).get("/auth/me").set("Authorization", `Bearer ${owner.session.access_token}`)
    expect(ownerMe.body.user.workspace).toMatchObject({ role: "owner", isOwner: true })
  })

  it("GET /chatbots/:id/actions never returns a custom action's header values in full", async () => {
    const { owner, chatbotId } = await makeOwnerWithCrawlPlus("secret-mask")
    // Inserted directly — creating via POST additionally requires an
    // active model top-up for the chatbot, unrelated to what this test
    // verifies (the GET masking behavior).
    await pool!.query(
      `insert into chatbot_actions (chatbot_id, name, description, http_method, url_template, headers_template, body_template, parameters)
       values ($1, 'call_api', 'test', 'GET', 'https://example.test/api', $2, null, '[]')`,
      [chatbotId, JSON.stringify({ Authorization: "Bearer sk_live_abcdef123456789" })],
    )

    const res = await request(app).get(`/chatbots/${chatbotId}/actions`).set("Authorization", `Bearer ${owner.session.access_token}`)
    expect(res.status).toBe(200)
    const action = res.body.actions[0]
    expect(action.headersTemplate.Authorization).not.toBe("Bearer sk_live_abcdef123456789")
    expect(action.headersTemplate.Authorization).toMatch(/6789$/)
    expect(action.headersTemplate.Authorization).not.toContain("sk_live")
  })

  it("editing an action's name only (headers echoed back masked) keeps the real Authorization header intact", async () => {
    const { owner, chatbotId } = await makeOwnerWithCrawlPlus("secret-preserve")
    const realHeader = "Bearer sk_live_abcdef123456789"
    const { rows } = await pool!.query<{ id: string }>(
      `insert into chatbot_actions (chatbot_id, name, description, http_method, url_template, headers_template, body_template, parameters)
       values ($1, 'call_api', 'test', 'GET', 'https://example.test/api', $2, null, '[]') returning id`,
      [chatbotId, JSON.stringify({ Authorization: realHeader })],
    )
    const actionId = rows[0].id
    // A top-up credit this chatbot needs for any real write through
    // updateAction (requireCustomActionTopup) — unrelated to what this test
    // verifies, just a precondition of the real code path.
    await pool!.query(
      `insert into chatbot_model_credits (chatbot_id, billing_period, model, credited_usd, stripe_checkout_session_id)
       values ($1, to_char(now(), 'YYYY-MM'), 'openai', 5, $2)`,
      [chatbotId, `cs_test_${randomUUID()}`],
    )

    const actionsService = await import("../../src/services/actions.service.js")
    const maskedEcho = "••••••••6789" // exactly what maskSecretValue(realHeader) produces

    const updated = await actionsService.updateAction(owner.session.access_token, chatbotId, actionId, {
      name: "call_api_renamed",
      description: "test",
      httpMethod: "GET",
      urlTemplate: "https://example.test/api",
      headersTemplate: { Authorization: maskedEcho },
      bodyTemplate: null,
      parameters: [],
    })

    expect(updated.name).toBe("call_api_renamed")
    // The service's own return value is the real row, unmasked — exactly
    // what the answering pipeline (getActionsForAnswering) would use to
    // actually call the external API.
    expect(updated.headersTemplate.Authorization).toBe(realHeader)

    const { rows: stored } = await pool!.query<{ headers_template: Record<string, string> }>(
      `select headers_template from chatbot_actions where id = $1`,
      [actionId],
    )
    expect(stored[0].headers_template.Authorization).toBe(realHeader)
  })
})
